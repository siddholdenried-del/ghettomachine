"""GhettoMachine's monospace faces (Bong Cult's Dungeon BBS look: a monospace face for readings, status and counters),
rendered at build time as fm1-base's own faces are (tools/gen_font.py's render and its glyph format, untrimmed).

  tools/gen_mono.py OUT.h          (fm1.toml gen; from app/, with Pillow and raqm)

IBM Plex Mono (assets/fonts, SIL OFL 1.1): FONT_MS, Regular 12 px, for the header's first line and small readings;
FONT_MB, SemiBold 15 px, for the knob strip's values; FONT_MT, SemiBold 18 px, for the page's title (the Acid Dub
Deck look, 0.5: space to Z only, the titles being capitals). The firmware carries only these pixels, not the fonts.
"""
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP.parent / "third_party" / "fm1-base" / "tools"))
import gen_font  # noqa: E402  (its render(): the same glyphs, alpha 0..15, as felucca_font.h's)

FACES = [("MS", "IBMPlexMono-Regular.ttf", 12, 126), ("MB", "IBMPlexMono-SemiBold.ttf", 15, 126),
         ("MT", "IBMPlexMono-SemiBold.ttf", 18, 90)]


def main(out):
    lines = ["/* generated by tools/gen_mono.py: IBM Plex Mono (SIL OFL 1.1) */", "#pragma once", ""]
    for name, ttf, px, last in FACES:
        h, glyphs = gen_font.render(str(APP / "assets" / "fonts" / ttf), px, 1, False, 32, last)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {gen_font.PAD}, 32, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
        print(f"gen_mono: FONT_{name} {ttf} {px} px, h {h}, advance {glyphs[ord('0') - 32][0]}, {len(data)} B")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
