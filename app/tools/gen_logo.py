"""BongTech GhettoMachine's boot screen (app.c app_splash): the logo, rendered once at build time.

  tools/gen_logo.py OUT.h          (fm1.toml gen; from app/, with Pillow)

Keep the GHETTO / MACHINE wordmark in Sedgwick Ave Display and BONGTECH in
Barlow Semi Condensed SemiBold. Each text mask uses 4-bit alpha. The exact
supplied square artwork fills all 240 × 240 pixels without cropping; nearest-
neighbour scaling and a 16-colour RGB565 palette preserve its pixel-art edges
in 28,800 B. The renderer composites the wordmarks over it in small stripes.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

APP = Path(__file__).resolve().parents[1]
NAME_TTF = APP / "assets" / "fonts" / "SedgwickAveDisplay-Regular.ttf"
TAG_TTF = APP.parent / "third_party" / "fm1-base" / "assets" / "fonts" / "BarlowSemiCondensed-SemiBold.ttf"
LINES, TAG = ("GHETTO", "MACHINE"), "BONGTECH"
W = 240
ART_PNG = APP / "assets" / "boot-grin.png"
ART_SIZE, ART_Y = W, 0
FIT, MAX_PX, TAG_PX, TAG_TRACK, TAG_GAP = 175, 56, 14, 3, 10


def text_w(font, s):
    return font.getlength(s)


def layout():
    probe = ImageFont.truetype(str(NAME_TTF), 100)
    size = min(MAX_PX, *(int(100 * FIT / text_w(probe, s)) for s in LINES))
    name_font = ImageFont.truetype(str(NAME_TTF), size)
    tag_font = ImageFont.truetype(str(TAG_TTF), TAG_PX)
    lh = round(size * 1.02)
    y0 = 49

    name = Image.new("L", (W, W), 0)
    d = ImageDraw.Draw(name)
    y = y0
    for s in LINES:                                   # each line centred, its em box's top at y (a canvas's "top")
        d.text((W / 2, y), s, font=name_font, fill=255, anchor="ma")
        y += lh

    tag = Image.new("L", (W, W), 0)
    d = ImageDraw.Draw(tag)
    widths = [text_w(tag_font, c) for c in TAG]
    x = (W - (sum(widths) + TAG_TRACK * len(TAG))) / 2  # (the canvas's letterSpacing follows every letter)
    for c, cw in zip(TAG, widths):
        d.text((x, y + TAG_GAP), c, font=tag_font, fill=255, anchor="la")
        x += cw + TAG_TRACK
    return size, name, tag


def packed(img, label):
    box = img.getbbox()
    if not box:
        raise SystemExit(f"gen_logo: {label} drew nothing")
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    px = img.load()
    out = bytearray()
    for y in range(y0, y1):
        for x in range(x0, x1, 2):
            a = (px[x, y] * 15 + 127) // 255
            b = (px[x + 1, y] * 15 + 127) // 255 if x + 1 < x1 else 0
            out.append(a << 4 | b)
    return x0, y0, w, h, bytes(out)


def c_array(name, data):
    rows = [", ".join(f"0x{v:02x}" for v in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def boot_art():
    im = Image.open(ART_PNG).convert("RGBA")
    # The square preview came from the supplied Affinity design. Show it uncropped.
    if im.size != (512, 512):
        raise SystemExit("gen_logo: expected the exact 512 × 512 square boot-art preview")
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    bg.alpha_composite(im)
    idx = bg.convert("RGB").resize((ART_SIZE, ART_SIZE), Image.Resampling.NEAREST).quantize(
        colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE
    )
    rgb = idx.getpalette()[:48]
    palette = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in zip(rgb[::3], rgb[1::3], rgb[2::3])]
    px = idx.tobytes()
    packed_pixels = bytes(px[i] << 4 | px[i+1] for i in range(0, len(px), 2))
    return (W-ART_SIZE)//2, ART_Y, ART_SIZE, palette, packed_pixels


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    size, name, tag = layout()
    parts = {"NAME": packed(name, "the name"), "TAG": packed(tag, "the tagline")}
    h = ["/* generated by tools/gen_logo.py: the boot screen's logo (Sedgwick Ave Display " f"{size} px; Barlow) */",
         "#pragma once", "#include <stdint.h>", ""]
    for k, (x, y, w, hh, data) in parts.items():
        h.append(f"#define LOGO_{k}_X {x}\n#define LOGO_{k}_Y {y}\n#define LOGO_{k}_W {w}\n#define LOGO_{k}_H {hh}")
        h.append(c_array(f"LOGO_{k}", data))
    ax, ay, aw, palette, data = boot_art()
    if (ax, ay, aw) != (0, 0, W) or len(data) != W * W // 2:
        raise SystemExit("gen_logo: artwork must cover the entire screen in packed 4-bit indices")
    h.append(f"#define LOGO_ART_X {ax}\n#define LOGO_ART_Y {ay}\n#define LOGO_ART_W {aw}\n#define LOGO_ART_H {aw}")
    h.append("static const uint16_t LOGO_ART_RGB[16] = {" + ", ".join(f"0x{v:04x}" for v in palette) + "};")
    h.append(c_array("LOGO_ART", data))
    Path(sys.argv[1]).write_text("\n".join(h))
    total = sum(len(p[4]) for p in parts.values()) + len(data) + 2*len(palette)
    print(f"gen_logo: {size} px, name {parts['NAME'][2]} x {parts['NAME'][3]} at y {parts['NAME'][1]}, "
          f"tag {parts['TAG'][2]} x {parts['TAG'][3]} at y {parts['TAG'][1]}: {total} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
