# Adapted voice order, compact decay knots, regenerated constants only (no samples).
from pathlib import Path
import math
import sys

RATE = 44100
# name, Hz, sweep Hz, pitch shift / 4 frames, metal, second osc Q8 ratio,
# noise mix and LP coefficient in Q8, reference T60 in ms.
VOICES = (
    ("BD", 50, 170, 9, 0, 0, 10, 20, 380),
    ("SD", 185, 60, 8, 0, 0, 170, 90, 190),
    ("LT", 95, 80, 9, 0, 0, 0, 0, 330),
    ("MT", 140, 90, 9, 0, 0, 0, 0, 290),
    ("HT", 200, 110, 9, 0, 0, 0, 0, 250),
    ("RS", 1700, 0, 6, 0, 0, 60, 160, 45),
    ("CP", 0, 0, 0, 0, 0, 255, 110, 260),
    ("CH", 330, 0, 0, 1, 640, 200, 230, 60),
    ("OH", 330, 0, 0, 1, 640, 200, 230, 420),
    ("CR", 400, 0, 0, 1, 590, 220, 200, 1300),
    ("RD", 450, 0, 0, 1, 610, 150, 220, 750),
    ("CB", 540, 0, 0, 1, 380, 0, 0, 230),
    ("TB", 0, 0, 0, 0, 0, 255, 200, 110),
)

def inc(hz):
    return round(hz * 2**32 / RATE)

out = [
    "/* SPDX-License-Identifier: GPL-3.0-only */",
    "/* Generated by app/tools/gen_707_tables.py. Constants only: no recordings. */",
    "static const drum707_spec_t SPEC[D7_NUM] = {",
]
for name, f0, sweep, pdec, metal, ratio, noise, hp, ms in VOICES:
    out.append(f"    [D7_{name}] = {{{inc(f0)}u, {inc(sweep)}u, {ratio}, {pdec}, {metal}, {noise}, {hp}}},")
out.extend(("};", "/* Every eight knob detents; last knot is the exact 127 endpoint. */",
            "static const uint32_t DECAY[D7_NUM][17] = {"))
for name, *_, ms in VOICES:
    knots = (round(math.exp(-math.log(1000) * 4 / (ms / 1000 * (0.25 + 2.25 * p / 127) * RATE)) * 2**24)
             for p in (*range(0, 127, 8), 127))
    out.append(f"    [D7_{name}] = {{" + ", ".join(str(i) for i in knots) + "},")
out.extend(("};", "/* One octave in each direction; 64 is exactly unity, Q16. */",
            "static const uint32_t TUNE[128] = {"))
for start in range(0, 128, 8):
    out.append("    " + ", ".join(str(round(65536 * 2 ** ((p - 64) / 64))) for p in range(start, start + 8)) + ",")
out.append("};")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
